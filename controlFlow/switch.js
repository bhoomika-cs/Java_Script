const score = 30

switch(score){
    case 10:
        console.log("D grade");
        break;
    case 20:
        console.log("C grade");
        break;
    case 30:
        console.log("B grade");
        break;
    case 40:
        console.log("A grade");
        break;
    case 50:
        console.log("A++ grade");
        break;
    default :
    console.log("FAIL");      
}

